const fold = (s: string) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

/** Suggestions for what the user has typed (accent and case insensitive, all words must match). */
export function suggest(query: string, limit = 8): string[] {
  const words = fold(query).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return CLASSICS.filter((c) => words.every((w) => fold(c).includes(w))).slice(0, limit);
}
